function normalizeRoleKey(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function expandPermissionKeys(keys) {
  if (keys.includes("*")) {
    return ALL_PERMISSION_KEYS;
  }
  return keys.filter((key) => ALL_PERMISSION_KEYS.includes(key));
}

